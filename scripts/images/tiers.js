/**
 * scripts/images/tiers.js — the ONE encoder and the ONE manifest writer for the site imagery.
 *
 * Two programs write `public/assets/**` and `src/data/generated/imageMeta.ts`:
 *   - scripts/optimize-images.js  rebuilds every slot from the originals in assets-src/ (bulk tool,
 *                                 needs the complete originals, which exist only on one machine);
 *   - scripts/content/            adds, removes or reorders photos of ONE slot from the committed
 *                                 files plus the new photos (the CMS Coordinator's operations).
 * Both import the limits, the file naming, the encoder and the manifest format from here, so a
 * photo added by either one ends up with the same tiers, sizes and names. Plain JavaScript because
 * optimize-images.js runs under bare `node`; types for the TypeScript callers are in tiers.d.ts.
 */
import { writeFile } from 'node:fs/promises';
import sharp from 'sharp';

export const MAX_BYTES = 200 * 1024;
export const FULL_EDGE = 1920;
export const MEDIUM_EDGE = 1280;
export const SMALL_EDGE = 800;
/** Per-tier quality ceilings: the smaller the tier, the less a lower quality shows on a phone. */
export const TIER_QUALITY = { full: 82, medium: 76, small: 70 };
export const BRAND_SMALL_EDGE = 240;
export const IMAGE_RE = /\.(jpe?g|png|webp|tiff?|heic)$/i;

export const slugify = (s) =>
  s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/\.[a-z0-9]+$/, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40);

/** Output base name of the n-th (1-based) photo of a slot: "03-" + slug of the source file name. */
export const outputName = (position, sourceFile) => `${String(position).padStart(2, '0')}-${slugify(sourceFile)}`;

/** Encodes to webp under MAX_BYTES: steps quality down, then shrinks the long edge. Returns final metadata. */
export const encodePhoto = async (src, out, edge, maxQuality) => {
  let currentEdge = edge;
  for (let attempt = 0; attempt < 6; attempt++) {
    const base = sharp(src)
      .rotate()
      .resize({ width: currentEdge, height: currentEdge, fit: 'inside', withoutEnlargement: true });
    for (let quality = maxQuality; quality >= 34; quality -= 6) {
      const buf = await base.clone().webp({ quality, effort: 5 }).toBuffer();
      if (buf.length <= MAX_BYTES) {
        await writeFile(out, buf);
        const meta = await sharp(buf).metadata();
        return { width: meta.width, height: meta.height, bytes: buf.length, quality };
      }
    }
    currentEdge = Math.round(currentEdge * 0.85);
  }
  throw new Error(`could not fit ${src} under ${MAX_BYTES} bytes`);
};

/** The three public paths of a photo, as the manifest stores them. */
export const photoPaths = (slotRel, name) => ({
  src: `/assets/${slotRel}/${name}.webp`,
  srcMedium: `/assets/${slotRel}/${name}-w${MEDIUM_EDGE}.webp`,
  srcSmall: `/assets/${slotRel}/${name}-w${SMALL_EDGE}.webp`,
});

/** The three file names of a photo inside its slot folder. */
export const photoFiles = (name) => ({
  full: `${name}.webp`,
  medium: `${name}-w${MEDIUM_EDGE}.webp`,
  small: `${name}-w${SMALL_EDGE}.webp`,
});

const META_HEADER = `// GENERATED by scripts/optimize-images.js — do not edit. Re-run: npm run optimize:assets\n`;
const META_TYPES =
  `export interface ImageAsset {\n  src: string;\n  srcMedium: string;\n  srcSmall: string;\n  width: number;\n  height: number;\n}\n\n` +
  `export interface ImageMeta {\n  hero: ImageAsset[];\n  about: ImageAsset[];\n  brand: ImageAsset[];\n  gallery: Record<string, ImageAsset[]>;\n  rental: Record<string, ImageAsset[]>;\n}\n\n`;
const META_EXPORT = 'export const IMAGE_META: ImageMeta = ';

/** The full text of src/data/generated/imageMeta.ts for a manifest object. */
export const renderImageMeta = (meta) => `${META_HEADER}${META_TYPES}${META_EXPORT}${JSON.stringify(meta, null, 2)};\n`;

/** Reads the manifest object back out of the generated file's text (it is written as JSON). */
export const parseImageMeta = (source) => {
  const start = source.indexOf(META_EXPORT);
  const end = source.lastIndexOf(';');
  if (start < 0 || end < start) throw new Error('imageMeta.ts: cannot find the IMAGE_META object — was the file edited by hand?');
  return JSON.parse(source.slice(start + META_EXPORT.length, end));
};
